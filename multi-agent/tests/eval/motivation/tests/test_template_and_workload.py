"""Template + workload allowlist tests (spec §5)."""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

import pytest


PROVENANCE_TEMPLATE_REL = "paper_outputs/motivation_data_provenance.md.template"

CANONICAL_KEYS = (
    "contexts_count",
    "wrong_context_failure_manual_baseline",
    "manual_steps_ssh",
    "reuse_time_savings",
)

PER_KEY_SUFFIXES = ("median", "iqr", "n_samples",
                    "source_sha256_list", "output_sha256", "cli")
SHARED = ("paper_git_sha", "multi_agent_git_sha", "wrong_ctx_seed")


def _template_text(paper_worktree: Path) -> str:
    return (paper_worktree / PROVENANCE_TEMPLATE_REL).read_text(encoding="utf-8")


def test_provenance_template_warning_lines(paper_worktree: Path):
    text = _template_text(paper_worktree)
    assert "template — real provenance MD generated by" in text
    assert "template；真 provenance 由后续 worktree" in text


def test_provenance_template_placeholder_inventory(paper_worktree: Path):
    text = _template_text(paper_worktree)
    found = set(re.findall(r"\{\{([a-zA-Z0-9_]+)\}\}", text))
    expected = set(SHARED)
    for key in CANONICAL_KEYS:
        for suffix in PER_KEY_SUFFIXES:
            expected.add(f"{key}_{suffix}")
    assert found == expected, (
        f"missing: {sorted(expected - found)}; extra: {sorted(found - expected)}"
    )


def test_provenance_template_cli_bash_valid(paper_worktree: Path):
    """Every ```bash fenced block must pass `bash -n`."""
    text = _template_text(paper_worktree)
    blocks = re.findall(r"```bash\n(.*?)\n```", text, re.DOTALL)
    assert blocks, "no ```bash blocks found in template"
    for block in blocks:
        r = subprocess.run(
            ["bash", "-n"],
            input=block, text=True, capture_output=True,
        )
        assert r.returncode == 0, f"bash -n failed on {block!r}\n{r.stderr}"


