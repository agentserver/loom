def test_motivation_e2e_not_in_stub_fulltable(ma_root: Path):
    """The motivation-e2e workload MUST NOT appear in any p3-stub-fulltable
    matrix/allowlist config that ships with this branch.

    Approach: scan the tree for `motivation-e2e` references outside our own
    tests/eval/{motivation,workloads/motivation-e2e} tree; if any exist in
    a stub-fulltable matrix file, fail. This is a static grep because the
    stub-fulltable worktree may not have been merged yet — the assertion
    is that no "already-shipped" main-table file lists this workload id.
    """
    import subprocess
    r = subprocess.run(
        ["git", "-C", str(ma_root), "grep", "-l", "-F", "motivation-e2e"],
        capture_output=True, text=True,
    )
    if r.returncode not in (0, 1):
        pytest.fail(f"git grep failed: {r.stderr}")
    hits = [line.strip() for line in r.stdout.splitlines() if line.strip()]
    allowed_prefixes = (
        "tests/eval/motivation/",
        "tests/eval/workloads/motivation-e2e/",
    )
    forbidden = [h for h in hits if not h.startswith(allowed_prefixes)]
    assert not forbidden, (
        f"motivation-e2e leaked into non-scaffold files: {forbidden}"
    )


def test_spec_yaml_first_line_scoped(workload_dir: Path):
    """spec §5 test_spec_yaml_first_line_scoped."""
    with (workload_dir / "spec.yaml").open("r", encoding="utf-8") as f:
        first = f.readline().rstrip("\n")
    expected = "# scaffold self-check only; NOT part of §6.3 main experiment 5-workload set"
    assert first == expected, f"first line: {first!r}"
