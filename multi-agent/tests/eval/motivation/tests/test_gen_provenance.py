"""gen_provenance.py tests (spec §5)."""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

import pytest


GEN = "tests/eval/motivation/gen_provenance.py"


def _run(args, cwd: Path):
    return subprocess.run(
        [sys.executable, *args], cwd=str(cwd), capture_output=True, text=True,
    )


def _git_init_clean(worktree: Path, seed_file: str = "seed.txt"):
    subprocess.check_call(["git", "init", "-q", str(worktree)])
    (worktree / seed_file).write_text("initial\n", encoding="utf-8")
    subprocess.check_call(
        ["git", "-C", str(worktree), "-c", "user.email=t@t", "-c", "user.name=t",
         "add", "-A"]
    )
    subprocess.check_call(
        ["git", "-C", str(worktree), "-c", "user.email=t@t", "-c", "user.name=t",
         "commit", "-q", "-m", "init"]
    )


def _make_fake_agg_dir(dirpath: Path):
    dirpath.mkdir(parents=True, exist_ok=True)
    recipes = {
        "contexts_count": {"median": 3, "iqr_low": 3, "iqr_high": 3},
        "wrong_context_failure_manual_baseline": {"median": 0.3, "iqr_low": 0.3, "iqr_high": 0.3},
        "manual_steps_ssh": {"median": 10, "iqr_low": 10, "iqr_high": 10},
        "reuse_time_savings": {"median": 60.0, "iqr_low": 55.0, "iqr_high": 65.0},
    }
    for k, r in recipes.items():
        r.update({"canonical_key": k, "n_samples": 3})
        (dirpath / f"{k}.json").write_text(json.dumps(r, sort_keys=True), encoding="utf-8")


def _make_fake_raw_dir(dirpath: Path):
    dirpath.mkdir(parents=True, exist_ok=True)
    for key in (
        "contexts_count",
        "wrong_context_failure_manual_baseline",
        "manual_steps_ssh",
        "reuse_time_savings",
    ):
        for i in range(3):
            (dirpath / f"{key}.rep{i}.json").write_text(
                json.dumps({"canonical_key": key, "raw_value": 1}),
                encoding="utf-8",
            )


def _make_fake_spec_yaml(dirpath: Path) -> Path:
    p = dirpath / "spec.yaml"
    p.write_text("id: motivation-e2e\nwrong_ctx_seed: 42\n", encoding="utf-8")
    return p


def _fake_template(dirpath: Path) -> Path:
    """Minimal template exercising all placeholders."""
    tpl = dirpath / "template.md"
    body_lines = [
        "> ⚠️ template — real provenance MD generated by p3-mini-case-run",
        "> ⚠️ 这是 template；真 provenance 由后续 worktree p3-mini-case-run 生成",
        "Meta paper={{paper_git_sha}} ma={{multi_agent_git_sha}} seed={{wrong_ctx_seed}}",
    ]
    for key in (
        "contexts_count",
        "wrong_context_failure_manual_baseline",
        "manual_steps_ssh",
        "reuse_time_savings",
    ):
        body_lines.extend([
            f"## {key}",
            f"median={{{{{key}_median}}}} iqr={{{{{key}_iqr}}}} n={{{{{key}_n_samples}}}}",
            f"src={{{{{key}_source_sha256_list}}}} out={{{{{key}_output_sha256}}}}",
            f"cli:```bash",
            f"{{{{{key}_cli}}}}",
            f"```",
        ])
    tpl.write_text("\n".join(body_lines) + "\n", encoding="utf-8")
    return tpl


def _setup(tmp_path: Path):
    paper = tmp_path / "paper"
    ma = tmp_path / "ma"
    paper.mkdir()
    ma.mkdir()
    _git_init_clean(paper, "paper-seed.txt")
    _git_init_clean(ma, "ma-seed.txt")
    agg = tmp_path / "agg"
    raw = tmp_path / "raw"
    _make_fake_agg_dir(agg)
    _make_fake_raw_dir(raw)
    spec = _make_fake_spec_yaml(tmp_path)
    template = _fake_template(tmp_path)
    return paper, ma, agg, raw, spec, template


def test_gen_provenance_dry_run_writes_smoke_path(ma_root: Path, tmp_path: Path):
    paper, ma, agg, raw, spec, template = _setup(tmp_path)
    r = _run([
        GEN,
        "--template", str(template),
        "--aggregate-dir", str(agg),
        "--raw-dir", str(raw),
        "--spec-yaml", str(spec),
        "--paper-worktree", str(paper),
        "--multi-agent-worktree", str(ma),
        "--out", str(tmp_path / "should-not-exist.md"),
        "--dry-run",
    ], cwd=ma_root)
    assert r.returncode == 0, r.stderr
    assert Path("/tmp/motivation_data_provenance.md.smoke").exists()
    assert not (tmp_path / "should-not-exist.md").exists()


def test_gen_provenance_unresolved_placeholder_rejected(ma_root: Path, tmp_path: Path):
    paper, ma, agg, raw, spec, template = _setup(tmp_path)
    # Add a bogus token to the template.
    template.write_text(template.read_text() + "\nleftover {{never_substituted}}\n",
                        encoding="utf-8")
    r = _run([
        GEN,
        "--template", str(template),
        "--aggregate-dir", str(agg),
        "--raw-dir", str(raw),
        "--spec-yaml", str(spec),
        "--paper-worktree", str(paper),
        "--multi-agent-worktree", str(ma),
        "--out", str(tmp_path / "out.md"),
        "--dry-run",
    ], cwd=ma_root)
    assert r.returncode == 2
    assert "ErrUnresolvedPlaceholder" in r.stderr


@pytest.mark.parametrize("case", ["unstaged", "staged", "untracked"])
def test_gen_provenance_dirty_tree_rejected(ma_root: Path, tmp_path: Path, case: str):
    """spec §5 test_gen_provenance_dirty_tree_rejected — 3 cases."""
    paper, ma, agg, raw, spec, template = _setup(tmp_path)

    if case == "unstaged":
        # Edit an existing tracked file, do NOT stage.
        (paper / "paper-seed.txt").write_text("modified", encoding="utf-8")
    elif case == "staged":
        new_file = paper / "new-tracked.txt"
        new_file.write_text("new", encoding="utf-8")
        subprocess.check_call(["git", "-C", str(paper), "add", str(new_file)])
    elif case == "untracked":
        (paper / "leftover.txt").write_text("leftover", encoding="utf-8")

    r = _run([
        GEN,
        "--template", str(template),
        "--aggregate-dir", str(agg),
        "--raw-dir", str(raw),
        "--spec-yaml", str(spec),
        "--paper-worktree", str(paper),
        "--multi-agent-worktree", str(ma),
        "--out", str(tmp_path / "out.md"),
        "--dry-run",
    ], cwd=ma_root)
    assert r.returncode == 2
    assert "ErrDirtyTree" in r.stderr
